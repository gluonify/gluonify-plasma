package io.gluonify.plasma.crystallon.client;

/**
 * JSON gateway of the client: writes the payload of a document and reads Crystallon's responses. The module does not impose a JSON library:
 * {@link #detect()} takes the one on the application's classpath, Jackson 3 first, otherwise Jackson 2. An application that
 * wants its own {@code ObjectMapper} (modules, naming...) passes it to {@link Jackson3Codec#of} or {@link Jackson2Codec#of}, or implements
 * these two methods, then calls {@code CrystallonClient.builder().json(codec)}.
 *
 * <p>The payload is a record or a bean annotated for Jackson (the code generated by the Crystallon editor is), or a {@code Map}. Dates are
 * written in ISO-8601 (never as timestamps), {@code BigDecimal} in plain decimal notation (never {@code 1E+3}).
 */
public interface PayloadCodec {

    /** @return the JSON (UTF-8) of the value @throws IllegalArgumentException if the value cannot be serialized */
    byte[] write(Object value);

    /** @return the value read; unknown properties are ignored @throws IllegalArgumentException if the JSON is invalid */
    <T> T read(byte[] json, Class<T> type);

    /**
     * Detects the JSON library at run time: {@code tools.jackson.databind.json.JsonMapper} (Jackson 3) first, otherwise
     * {@code com.fasterxml.jackson.databind.ObjectMapper} (Jackson 2, with {@code JavaTimeModule} if present: without it, Jackson 2 rejects
     * {@code LocalDate}).
     *
     * @throws IllegalStateException if neither is present
     */
    static PayloadCodec detect() {
        if (present("tools.jackson.databind.json.JsonMapper")) {
            return Jackson3Codec.create();
        }
        if (present("com.fasterxml.jackson.databind.ObjectMapper")) {
            return Jackson2Codec.create();
        }
        throw new IllegalStateException("No JSON library for the Crystallon client: add Jackson 3 (tools.jackson.core:jackson-databind) or Jackson 2 "
                + "(com.fasterxml.jackson.core:jackson-databind, and com.fasterxml.jackson.datatype:jackson-datatype-jsr310 for dates), "
                + "or give your own PayloadCodec to CrystallonClient.builder().json(...)");
    }

    /** Presence of a class, without loading it more than necessary (constant literal: recognized by the native image). */
    private static boolean present(final String className) {
        try {
            Class.forName(className);
            return true;
        }
        catch (final ClassNotFoundException | LinkageError e) {
            return false;
        }
    }
}
