package io.gluonify.plasma.quarkus.mcp;

import static org.junit.jupiter.api.Assertions.*;

import java.util.ArrayList;
import java.util.List;
import java.util.Map;
import org.junit.jupiter.api.Test;
import tools.jackson.databind.JsonNode;
import tools.jackson.databind.ObjectMapper;

/** Reading the tools of toolboxes: proxies, inherited and bridge methods, parameter orders, declared schemas, warnings. */
class McpRegistryGapsTest {
    static final ObjectMapper M = new ObjectMapper();

    record Args(String text) {
    }

    static class Plain implements McpToolbox {
        @McpTool(description = "echo")
        public String echo(final Args args) {
            return args.text();
        }

        @McpTool(description = "who am i")
        public String whoAmI(final McpCaller caller) {
            return caller.subject();
        }

        @McpTool(description = "both, caller first")
        public String callerFirst(final McpCaller caller, final Args args) {
            return caller.subject() + args.text();
        }

        @McpTool(description = "both, caller last")
        public String callerLast(final Args args, final McpCaller caller) {
            return args.text() + caller.subject();
        }

        public static String notATool() {
            return "static";
        }

        @McpTool(description = "static tools are not read")
        public static String staticTool() {
            return "static";
        }
    }

    /** A subclass generated by the container: its name carries the marker the registry looks for. */
    static class Plain_Subclass extends Plain {
    }

    static class Plain_ClientProxy extends Plain {
    }

    interface Handler<T> {
        String handle(T value);
    }

    static class Bridged implements McpToolbox, Handler<Args> {
        @Override
        @McpTool(name = "bridged", description = "the compiler adds a bridge method for the generic interface")
        public String handle(final Args value) {
            return value.text();
        }
    }

    static class Inherited extends Plain {
        @Override
        @McpTool(description = "echo, overridden")
        public String echo(final Args args) {
            return "again " + args.text();
        }
    }

    static class TwoCallers implements McpToolbox {
        @McpTool(description = "x")
        public String t(final McpCaller a, final McpCaller b) {
            return "";
        }
    }

    static class ArrayDeclared implements McpToolbox {
        @McpTool(description = "x", inputSchema = "[1,2]")
        public String t() {
            return "";
        }
    }

    // compile-time constants only in an annotation: 8 characters doubled eleven times is 16,384
    static final String D0 = "xxxxxxxx";
    static final String D1 = D0 + D0;
    static final String D2 = D1 + D1;
    static final String D3 = D2 + D2;
    static final String D4 = D3 + D3;
    static final String D5 = D4 + D4;
    static final String D6 = D5 + D5;
    static final String D7 = D6 + D6;
    static final String D8 = D7 + D7;
    static final String D9 = D8 + D8;
    static final String D10 = D9 + D9;
    static final String D11 = D10 + D10;

    static class HugeSchema implements McpToolbox {
        @McpTool(description = "x", inputSchema = "{\"type\":\"object\",\"description\":\"" + D11 + "\"}")
        public String t() {
            return "";
        }
    }

    static class Declared implements McpToolbox {
        @McpTool(description = "  declared  ", inputSchema = "{\"type\":\"object\",\"properties\":{\"q\":{\"type\":\"string\"}}}", write = true)
        public String search(final Map<String, Object> arguments) {
            return "";
        }
    }

    static class NoTool implements McpToolbox {
        public String helper() {
            return "";
        }
    }

    static McpRegistry registry(final List<String> warnings, final Object... toolboxes) {
        return McpRegistry.of(List.of(toolboxes), M, warnings::add);
    }

    @Test
    void parametersMayComeInEitherOrderAndStaticMethodsAreNotTools() {
        final McpRegistry r = registry(new ArrayList<>(), new Plain());
        assertEquals(List.of("caller_first", "caller_last", "echo", "who_am_i"), r.tools().stream().map(McpRegistry.Tool::name).toList());
        final McpRegistry.Tool first = r.get("caller_first").orElseThrow();
        assertEquals(0, first.caller());
        assertEquals(1, first.argument());
        final McpRegistry.Tool last = r.get("caller_last").orElseThrow();
        assertEquals(1, last.caller());
        assertEquals(0, last.argument());
        final McpRegistry.Tool me = r.get("who_am_i").orElseThrow();
        assertEquals(-1, me.argument());
        assertEquals(List.of(), me.required());
        assertEquals("object", me.inputSchema().get("type").asString());
        assertTrue(r.get("static_tool").isEmpty());
        assertEquals(4, r.size());
    }

    @Test
    void containerGeneratedSubclassesAreReadThroughTheirBeanClass() {
        for (final Object proxy : new Object[]{new Plain_Subclass(), new Plain_ClientProxy()}) {
            final List<String> warnings = new ArrayList<>();
            assertEquals(4, registry(warnings, proxy).size(), proxy.getClass().getSimpleName());
            assertEquals(List.of(), warnings);
        }
    }

    @Test
    void aBridgeMethodIsNotASecondTool() {
        final McpRegistry r = registry(new ArrayList<>(), new Bridged());
        assertEquals(List.of("bridged"), r.tools().stream().map(McpRegistry.Tool::name).toList());
    }

    @Test
    void anOverridingMethodHidesTheParentsAndTheInheritedToolsStay() {
        final McpRegistry r = registry(new ArrayList<>(), new Inherited());
        assertEquals(4, r.size());
        assertEquals("echo, overridden", r.get("echo").orElseThrow().description(), "an annotated override replaces the parent's declaration");
        assertEquals("again x", assertDoesNotThrow(() -> r.get("echo").orElseThrow().method().invoke(r.get("echo").orElseThrow().target(), new Args("x"))));
    }

    @Test
    void anOverrideWithoutTheAnnotationKeepsTheParentsToolAndCallsTheOverride() throws Exception {
        class Quiet extends Plain {
            @Override
            public String echo(final Args args) {
                return "override of " + args.text();
            }
        }
        final McpRegistry r = registry(new ArrayList<>(), new Quiet());
        assertEquals(4, r.size(), "the tool is listed once");
        final McpRegistry.Tool echo = r.get("echo").orElseThrow();
        assertEquals("echo", echo.description(), "the parent's annotation describes it");
        assertEquals(Quiet.class, echo.method().getDeclaringClass(), "the call goes through the overriding method");
        assertEquals("override of x", echo.method().invoke(echo.target(), new Args("x")));
        assertEquals(1, r.tools().stream().filter(t -> t.name().equals("echo")).count());
    }

    @Test
    void anInheritedToolIsFoundOnTheSubclass() {
        class Child extends Plain {
        }
        assertEquals(4, registry(new ArrayList<>(), new Child()).size());
    }

    @Test
    void aToolboxWithoutToolsIsWarnedAbout() {
        final List<String> warnings = new ArrayList<>();
        assertEquals(0, registry(warnings, new NoTool()).size());
        assertEquals(1, warnings.size());
        assertTrue(warnings.get(0).contains(NoTool.class.getName()) && warnings.get(0).contains("@RegisterForReflection"), warnings.get(0));
    }

    @Test
    void aDeclaredSchemaIsKeptAsIsAndTheDescriptionStripped() {
        final McpRegistry.Tool t = registry(new ArrayList<>(), new Declared()).get("search").orElseThrow();
        assertEquals("declared", t.description());
        assertTrue(t.write());
        assertEquals("string", t.inputSchema().at("/properties/q/type").asString());
        final JsonNode described = t.describe(M);
        assertFalse(described.at("/annotations/readOnlyHint").asBoolean());
        assertTrue(described.get("write").asBoolean());
    }

    static String refusal(final Object... toolboxes) {
        return assertThrows(IllegalStateException.class, () -> registry(new ArrayList<>(), toolboxes)).getMessage();
    }

    @Test
    void signaturesAndSchemasThatCannotWorkStopTheStartup() {
        assertTrue(refusal(new TwoCallers()).contains("one arguments parameter and optionally an McpCaller, found also McpCaller"));
        assertTrue(refusal(new ArrayDeclared()).contains("the input schema must be a JSON object"));
        assertTrue(refusal(new HugeSchema()).contains("larger than 16 KiB"));
    }

    @Test
    void namesAreWrittenInSnakeCase() {
        assertEquals("order_stats", McpRegistry.snake("orderStats"));
        assertEquals("httpstatus", McpRegistry.snake("HTTPStatus"));
        assertEquals("a_bc", McpRegistry.snake("aBC"));
        assertEquals("plain", McpRegistry.snake("plain"));
        assertEquals("", McpRegistry.snake(""));
    }
}
